-- PromScan application schema.
-- This migration is additive and can be applied after the catalog-only SQL
-- from the database branch. It deliberately keeps one PostgreSQL database and
-- separates future domains with schemas instead of creating cross-database FKs.

CREATE SCHEMA IF NOT EXISTS promscan;
CREATE SCHEMA IF NOT EXISTS promscan_api;
CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS measurements;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS promscan.equipment (
    id                  text PRIMARY KEY,
    qr_id               text,
    name                text NOT NULL,
    manufacturer        text,
    model               text NOT NULL DEFAULT '',
    serial_number       text,
    inventory_number    text,
    category            text NOT NULL DEFAULT 'equipment',
    location            text,
    state               text CHECK (state IN ('operational', 'maintenance', 'fault')),
    commissioned_at     date,
    service_life_years  integer CHECK (service_life_years > 0),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE promscan.equipment ADD COLUMN IF NOT EXISTS qr_id text;
CREATE UNIQUE INDEX IF NOT EXISTS equipment_qr_id_uidx
    ON promscan.equipment (qr_id)
    WHERE qr_id IS NOT NULL AND btrim(qr_id) <> '';
CREATE INDEX IF NOT EXISTS equipment_category_idx
    ON promscan.equipment (category);

CREATE TABLE IF NOT EXISTS promscan.equipment_aliases (
    alias               text PRIMARY KEY,
    equipment_id        text NOT NULL REFERENCES promscan.equipment(id) ON DELETE RESTRICT,
    source              text NOT NULL DEFAULT 'registry',
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS equipment_aliases_equipment_idx
    ON promscan.equipment_aliases (equipment_id);

CREATE TABLE IF NOT EXISTS promscan.equipment_specs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    label           text NOT NULL,
    value           text NOT NULL,
    unit            text,
    sort_order      integer NOT NULL DEFAULT 0,
    UNIQUE (equipment_id, label)
);

CREATE TABLE IF NOT EXISTS promscan.equipment_nodes (
    id              text PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE RESTRICT,
    public_id       text,
    name            text NOT NULL,
    description     text,
    offset_x        double precision NOT NULL DEFAULT 0,
    offset_y        double precision NOT NULL DEFAULT 0,
    offset_z        double precision NOT NULL DEFAULT 0,
    radius          double precision NOT NULL DEFAULT 0.25 CHECK (radius > 0),
    sort_order      integer NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (equipment_id, public_id)
);

ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS public_id text;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS description text;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS offset_x double precision NOT NULL DEFAULT 0;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS offset_y double precision NOT NULL DEFAULT 0;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS offset_z double precision NOT NULL DEFAULT 0;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS radius double precision NOT NULL DEFAULT 0.25;
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE promscan.equipment_nodes ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS equipment_nodes_equipment_idx
    ON promscan.equipment_nodes (equipment_id, sort_order);

CREATE TABLE IF NOT EXISTS promscan.node_specs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id         text NOT NULL REFERENCES promscan.equipment_nodes(id) ON DELETE CASCADE,
    label           text NOT NULL,
    value           text NOT NULL,
    unit            text,
    sort_order      integer NOT NULL DEFAULT 0,
    UNIQUE (node_id, label)
);

CREATE TABLE IF NOT EXISTS promscan_api.object_metadata (
    id                  text PRIMARY KEY,
    object_key          text NOT NULL UNIQUE,
    bucket              text NOT NULL,
    mime_type           text NOT NULL,
    byte_size           bigint NOT NULL CHECK (byte_size >= 0),
    sha256              char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    etag                text,
    equipment_id        text REFERENCES promscan.equipment(id) ON DELETE SET NULL,
    inspection_id       text,
    report_id           text,
    purpose             text NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS object_metadata_equipment_idx
    ON promscan_api.object_metadata (equipment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS object_metadata_inspection_idx
    ON promscan_api.object_metadata (inspection_id);
CREATE INDEX IF NOT EXISTS object_metadata_report_idx
    ON promscan_api.object_metadata (report_id);

CREATE TABLE IF NOT EXISTS promscan_api.inspections (
    id                  text PRIMARY KEY,
    equipment_id        text NOT NULL REFERENCES promscan.equipment(id) ON DELETE RESTRICT,
    status              text NOT NULL DEFAULT 'completed'
                            CHECK (status IN ('processing', 'completed', 'failed')),
    source              text NOT NULL DEFAULT 'android',
    model               text,
    image_object_id     text REFERENCES promscan_api.object_metadata(id) ON DELETE SET NULL,
    result              jsonb NOT NULL DEFAULT '{}'::jsonb
                            CHECK (jsonb_typeof(result) = 'object'),
    error_message       text,
    started_at          timestamptz NOT NULL DEFAULT now(),
    completed_at        timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS inspections_equipment_idx
    ON promscan_api.inspections (equipment_id, created_at DESC);

CREATE TABLE IF NOT EXISTS promscan_api.defects (
    id                  text PRIMARY KEY,
    inspection_id       text NOT NULL REFERENCES promscan_api.inspections(id) ON DELETE CASCADE,
    equipment_id        text NOT NULL REFERENCES promscan.equipment(id) ON DELETE RESTRICT,
    public_id           text NOT NULL,
    node_id             text,
    type                text NOT NULL,
    title               text NOT NULL,
    confidence          double precision NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    severity            text NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    polygon             jsonb,
    bbox                jsonb,
    offset_from_qr      jsonb,
    analysis            text,
    recommendation      text,
    model               text,
    detected_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (inspection_id, public_id)
);

CREATE INDEX IF NOT EXISTS defects_equipment_idx
    ON promscan_api.defects (equipment_id, detected_at DESC);
CREATE INDEX IF NOT EXISTS defects_inspection_idx
    ON promscan_api.defects (inspection_id);

CREATE TABLE IF NOT EXISTS promscan_api.defect_resolutions (
    defect_id           text PRIMARY KEY REFERENCES promscan_api.defects(id) ON DELETE CASCADE,
    resolution_status   text NOT NULL CHECK (resolution_status IN ('fixed_on_site', 'parts_required', 'false_positive')),
    comment             text,
    required_parts      jsonb NOT NULL DEFAULT '[]'::jsonb
                            CHECK (jsonb_typeof(required_parts) = 'array'),
    is_false_positive   boolean NOT NULL DEFAULT false,
    resolved_by         text,
    resolved_at         timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS promscan_api.defect_resolution_history (
    id                  text PRIMARY KEY,
    defect_id           text NOT NULL REFERENCES promscan_api.defects(id) ON DELETE CASCADE,
    resolution_status   text NOT NULL CHECK (resolution_status IN ('fixed_on_site', 'parts_required', 'false_positive')),
    comment             text,
    required_parts      jsonb NOT NULL DEFAULT '[]'::jsonb
                            CHECK (jsonb_typeof(required_parts) = 'array'),
    is_false_positive   boolean NOT NULL DEFAULT false,
    resolved_by         text,
    created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS promscan_api.reports (
    id                  text PRIMARY KEY,
    report_id           text NOT NULL UNIQUE,
    equipment_id        text NOT NULL REFERENCES promscan.equipment(id) ON DELETE RESTRICT,
    inspection_id       text REFERENCES promscan_api.inspections(id) ON DELETE SET NULL,
    node_id             text,
    defect_id           text REFERENCES promscan_api.defects(id) ON DELETE SET NULL,
    defect_title        text,
    resolution_status   text NOT NULL CHECK (resolution_status IN ('fixed_on_site', 'parts_required', 'false_positive')),
    workflow_status     text NOT NULL DEFAULT 'open'
                            CHECK (workflow_status IN ('open', 'in_progress', 'closed')),
    comment             text,
    source              text NOT NULL DEFAULT 'android',
    idempotency_key     text UNIQUE,
    request_hash        char(64),
    document_object_id  text REFERENCES promscan_api.object_metadata(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS reports_equipment_idx
    ON promscan_api.reports (equipment_id, created_at DESC);
CREATE INDEX IF NOT EXISTS reports_status_created_idx
    ON promscan_api.reports (workflow_status, created_at DESC);
CREATE INDEX IF NOT EXISTS reports_defect_idx
    ON promscan_api.reports (defect_id);

CREATE TABLE IF NOT EXISTS audit.events (
    id                  text PRIMARY KEY,
    event_type          text NOT NULL,
    actor_id            text,
    equipment_id        text,
    inspection_id       text,
    report_id           text,
    payload             jsonb NOT NULL DEFAULT '{}'::jsonb
                            CHECK (jsonb_typeof(payload) = 'object'),
    created_at           timestamptz NOT NULL DEFAULT now()
);

COMMENT ON SCHEMA promscan IS 'PromScan application data in one PostgreSQL database';
COMMENT ON SCHEMA promscan_api IS
    'Android API persistence projection; catalog identity remains in promscan';
COMMENT ON TABLE promscan.equipment_nodes IS
    'AR components; offset_x/y/z are metres from the public QR anchor and radius is metres';
COMMENT ON TABLE promscan_api.object_metadata IS
    'Metadata only. Photo/PDF/document bytes remain in external S3-compatible storage.';
COMMENT ON TABLE promscan_api.defect_resolutions IS
    'Current engineer decision, intentionally separate from workflow_status on reports';
