-- Store equipment passport binaries and metadata in the same PostgreSQL DB.
-- Existing equipment_documents rows are preserved and can be filled by importer.

CREATE TABLE IF NOT EXISTS promscan.equipment_documents (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    document_type   text NOT NULL,
    file_name       text NOT NULL,
    source_provider text NOT NULL DEFAULT 'local_import',
    source_path     text NOT NULL,
    mime_type       text NOT NULL DEFAULT 'application/pdf',
    created_at      timestamptz NOT NULL DEFAULT now(),
    content         bytea,
    sha256          bytea,
    byte_size       bigint,
    imported_at     timestamptz,
    UNIQUE (equipment_id, document_type, source_path)
);

ALTER TABLE promscan.equipment_documents
    ADD COLUMN IF NOT EXISTS content bytea;
ALTER TABLE promscan.equipment_documents
    ADD COLUMN IF NOT EXISTS sha256 bytea;
ALTER TABLE promscan.equipment_documents
    ADD COLUMN IF NOT EXISTS byte_size bigint;
ALTER TABLE promscan.equipment_documents
    ADD COLUMN IF NOT EXISTS imported_at timestamptz;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'equipment_documents_content_metadata_check'
          AND conrelid = 'promscan.equipment_documents'::regclass
    ) THEN
        ALTER TABLE promscan.equipment_documents
            ADD CONSTRAINT equipment_documents_content_metadata_check
            CHECK (
                (content IS NULL AND sha256 IS NULL AND byte_size IS NULL AND imported_at IS NULL)
                OR
                (content IS NOT NULL AND octet_length(content) > 0
                 AND sha256 IS NOT NULL AND octet_length(sha256) = 32
                 AND byte_size = octet_length(content) AND imported_at IS NOT NULL)
            );
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS equipment_documents_equipment_idx
    ON promscan.equipment_documents (equipment_id, document_type, file_name);

COMMENT ON COLUMN promscan.equipment_documents.content IS
    'Complete PDF bytes stored in PostgreSQL bytea; NULL means metadata-only and not downloadable';
COMMENT ON COLUMN promscan.equipment_documents.source_path IS
    'Source provenance label only. Runtime code must never fetch this path';
