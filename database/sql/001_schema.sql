-- PromScan pump catalog schema. PostgreSQL 15+.
-- Apply while connected to the target database, for example: psql -d promscan -f 001_schema.sql

CREATE SCHEMA IF NOT EXISTS promscan;

CREATE TABLE IF NOT EXISTS promscan.equipment (
    id                  text PRIMARY KEY,
    name                text NOT NULL,
    manufacturer        text,
    model               text NOT NULL,
    serial_number       text UNIQUE,
    inventory_number    text UNIQUE,
    category            text NOT NULL,
    location            text,
    state               text CHECK (state IN ('operational', 'maintenance', 'fault')),
    commissioned_at     date,
    service_life_years  integer CHECK (service_life_years > 0),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS equipment_category_idx
    ON promscan.equipment (category);

CREATE TABLE IF NOT EXISTS promscan.equipment_specs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    label           text NOT NULL,
    value           text NOT NULL,
    unit            text,
    sort_order      integer NOT NULL DEFAULT 0,
    UNIQUE (equipment_id, label)
);

CREATE INDEX IF NOT EXISTS equipment_specs_equipment_idx
    ON promscan.equipment_specs (equipment_id, sort_order, id);

CREATE TABLE IF NOT EXISTS promscan.equipment_nodes (
    id              text PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    name            text NOT NULL,
    sort_order      integer NOT NULL DEFAULT 0,
    UNIQUE (equipment_id, name),
    UNIQUE (equipment_id, id)
);

CREATE INDEX IF NOT EXISTS equipment_nodes_equipment_idx
    ON promscan.equipment_nodes (equipment_id, sort_order);

CREATE TABLE IF NOT EXISTS promscan.node_specs (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id         text NOT NULL REFERENCES promscan.equipment_nodes(id) ON DELETE CASCADE,
    label           text NOT NULL,
    value           text NOT NULL,
    unit            text,
    sort_order      integer NOT NULL DEFAULT 0,
    UNIQUE (node_id, label)
);

CREATE INDEX IF NOT EXISTS node_specs_node_idx
    ON promscan.node_specs (node_id, sort_order, id);

CREATE TABLE IF NOT EXISTS promscan.equipment_documents (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    document_type   text NOT NULL,
    file_name       text NOT NULL,
    source_provider text NOT NULL,
    source_path     text NOT NULL,
    mime_type       text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (equipment_id, document_type, source_path)
);

CREATE INDEX IF NOT EXISTS equipment_documents_equipment_idx
    ON promscan.equipment_documents (equipment_id);

CREATE TABLE IF NOT EXISTS promscan.maintenance_records (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    text NOT NULL REFERENCES promscan.equipment(id) ON DELETE CASCADE,
    maintenance_date date NOT NULL,
    work_type       text NOT NULL,
    description     text NOT NULL,
    performed_by    text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS maintenance_records_history_idx
    ON promscan.maintenance_records (equipment_id, maintenance_date DESC);

COMMENT ON SCHEMA promscan IS 'Pump catalog and passport data for PromScan';
COMMENT ON TABLE promscan.equipment IS 'Equipment identity and the EquipmentSummary/EquipmentDetail fields';
COMMENT ON TABLE promscan.equipment_specs IS 'Ordered label/value/unit properties serialized as SpecItem[]';
COMMENT ON TABLE promscan.equipment_nodes IS 'Pump components referenced by inspection defects';
COMMENT ON TABLE promscan.node_specs IS 'Passport properties for an equipment component';
COMMENT ON TABLE promscan.equipment_documents IS 'Document metadata; binaries remain in external file storage';
COMMENT ON TABLE promscan.maintenance_records IS 'Verified maintenance history; no events are seeded from blank passport fields';
