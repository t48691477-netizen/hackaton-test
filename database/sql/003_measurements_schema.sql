-- Time-series schema for vibration and temperature readings.
-- Apply after 001_schema.sql and 002_seed_pumps.sql.

CREATE TABLE IF NOT EXISTS promscan.measurement_channels (
    id              text PRIMARY KEY,
    name            text NOT NULL,
    modality        text NOT NULL CHECK (modality IN ('vibration', 'temperature', 'speed')),
    unit            text NOT NULL,
    measurement_location text NOT NULL,
    description     text NOT NULL,
    sort_order      integer NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS promscan.sensor_devices (
    id                      text PRIMARY KEY,
    equipment_id            text REFERENCES promscan.equipment(id) ON DELETE SET NULL,
    external_identifier     text UNIQUE,
    name                    text NOT NULL,
    manufacturer            text,
    model                   text,
    serial_number           text UNIQUE,
    measurement_location    text,
    installed_at            timestamptz,
    retired_at              timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    CHECK (retired_at IS NULL OR installed_at IS NULL OR retired_at >= installed_at)
);

CREATE INDEX IF NOT EXISTS sensor_devices_equipment_idx
    ON promscan.sensor_devices (equipment_id);

CREATE TABLE IF NOT EXISTS promscan.sensor_channels (
    sensor_id       text NOT NULL REFERENCES promscan.sensor_devices(id) ON DELETE CASCADE,
    channel_id      text NOT NULL REFERENCES promscan.measurement_channels(id) ON DELETE RESTRICT,
    PRIMARY KEY (sensor_id, channel_id)
);

CREATE INDEX IF NOT EXISTS sensor_channels_channel_idx
    ON promscan.sensor_channels (channel_id, sensor_id);

CREATE TABLE IF NOT EXISTS promscan.measurement_import_batches (
    id                  text PRIMARY KEY,
    dataset_code        text NOT NULL,
    source_provider     text NOT NULL,
    source_path         text NOT NULL,
    source_file         text NOT NULL,
    source_format       text NOT NULL,
    provenance          text NOT NULL CHECK (provenance IN ('synthetic_demo', 'unverified', 'verified_production')),
    import_status       text NOT NULL DEFAULT 'catalogued' CHECK (import_status IN ('catalogued', 'loaded', 'rejected')),
    source_row_count    integer NOT NULL CHECK (source_row_count >= 0),
    recorded_timezone   text,
    observed_start      timestamp without time zone,
    observed_end        timestamp without time zone,
    equipment_id        text REFERENCES promscan.equipment(id) ON DELETE SET NULL,
    source_description  text NOT NULL,
    imported_at         timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_provider, source_path),
    CHECK (observed_end IS NULL OR observed_start IS NULL OR observed_end >= observed_start),
    CHECK ((import_status = 'loaded') = (imported_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS measurement_import_batches_equipment_idx
    ON promscan.measurement_import_batches (equipment_id, observed_start DESC);

CREATE TABLE IF NOT EXISTS promscan.measurements (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        text NOT NULL REFERENCES promscan.measurement_import_batches(id) ON DELETE CASCADE,
    channel_id      text NOT NULL REFERENCES promscan.measurement_channels(id) ON DELETE RESTRICT,
    sensor_id       text,
    measured_at     timestamp without time zone NOT NULL,
    numeric_value   numeric(18, 6) NOT NULL,
    quality_status  text NOT NULL DEFAULT 'unverified' CHECK (quality_status IN ('unverified', 'valid', 'suspect', 'invalid')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (batch_id, channel_id, measured_at),
    FOREIGN KEY (sensor_id, channel_id)
        REFERENCES promscan.sensor_channels (sensor_id, channel_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS measurements_channel_time_idx
    ON promscan.measurements (channel_id, measured_at DESC);

CREATE INDEX IF NOT EXISTS measurements_sensor_time_idx
    ON promscan.measurements (sensor_id, measured_at DESC)
    WHERE sensor_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS measurements_batch_time_idx
    ON promscan.measurements (batch_id, measured_at);

CREATE TABLE IF NOT EXISTS promscan.measurement_diagnoses (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        text NOT NULL REFERENCES promscan.measurement_import_batches(id) ON DELETE CASCADE,
    modality        text NOT NULL CHECK (modality IN ('vibration', 'temperature')),
    measured_at     timestamp without time zone NOT NULL,
    source_label    text NOT NULL,
    diagnosis_level text NOT NULL CHECK (diagnosis_level IN ('normal', 'warning', 'alarm', 'unclassified')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (batch_id, modality, measured_at)
);

CREATE INDEX IF NOT EXISTS measurement_diagnoses_batch_time_idx
    ON promscan.measurement_diagnoses (batch_id, measured_at DESC);

CREATE TABLE IF NOT EXISTS promscan.measurement_thresholds (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id      text NOT NULL REFERENCES promscan.measurement_channels(id) ON DELETE CASCADE,
    level           text NOT NULL CHECK (level IN ('warning', 'critical')),
    comparison      text NOT NULL CHECK (comparison IN ('gt', 'gte', 'lt', 'lte')),
    threshold_value numeric(18, 6) NOT NULL,
    source_document text NOT NULL,
    notes           text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (channel_id, level, source_document)
);

CREATE INDEX IF NOT EXISTS measurement_thresholds_channel_idx
    ON promscan.measurement_thresholds (channel_id, level);

COMMENT ON TABLE promscan.measurement_channels IS 'Logical measurement quantities; source files do not identify physical sensor devices';
COMMENT ON TABLE promscan.sensor_devices IS 'Physical sensor registry for future use; no real devices are inferred from demo spreadsheets';
COMMENT ON TABLE promscan.sensor_channels IS 'Many-to-many mapping of physical sensors to measured channels';
COMMENT ON TABLE promscan.measurement_import_batches IS 'Source and provenance manifest; rejected demo files are retained as metadata but their rows are not loaded';
COMMENT ON TABLE promscan.measurements IS 'Long-form numeric time series; measured_at preserves source local time without an assumed timezone; sensor_id is nullable when the source does not identify a device';
COMMENT ON TABLE promscan.measurement_diagnoses IS 'Source diagnosis labels kept alongside readings; not a server-side diagnosis';
COMMENT ON TABLE promscan.measurement_thresholds IS 'Thresholds transcribed from source descriptions, retained with their provenance';
