package ru.cyber102.arinspector.data

/**
 * Офлайн-сценарий для ассистента «Моттэл».
 * Те же ключевые ответы, что отдаёт mock-бэкенд: питч не должен зависеть от сети.
 */
object MottelScript {

    private val rules: List<Pair<List<String>, String>> = listOf(
        listOf("дефект", "находк", "что делать", "анализ") to
            "По кадру три находки: коррозия фланца №3 (94%), трещина корпуса (87%) и лёгкая " +
                "коррозия муфты (72%). Начинай с фланца: снять давление, заменить прокладку, " +
                "протянуть крепёж моментом 120 Н·м. Корпус — УЗК-контроль до следующего пуска.",

        listOf("запчаст", "заказ", "купить", "склад") to
            "Нужны: прокладка DN100 — 1 шт., болты М20×80 — 8 шт., преобразователь ржавчины — 1 л. " +
                "Корпус насоса заказывать раньше УЗК-контроля не стоит.",

        listOf("акт", "отчёт", "отчет", "документ", "pdf") to
            "Акт собирается в карточке узла: статус → комментарий → «Зафиксировать акт». " +
                "Номер присвоит сервер, PDF уйдёт в мессенджер или на почту прямо с места.",

        listOf("qr", "код", "скан") to
            "QR на оборудовании — адрес узла. Навёл камеру — паспорт с сервера — маркеры встают " +
                "относительно кода. Держи 20–30 см, следи за светом и бликами.",

        listOf("ар", "ar", "маркер", "якор") to
            "Якорь ставится на плоскость QR. Если ARCore не видит плоскость — нажми «Разместить», " +
                "он поставит якорь в центр экрана. На эмуляторе работает режим SIM AR."
    )

    private const val FALLBACK =
        "Я на связи. Могу разобрать находки, собрать список запчастей, " +
            "подсказать по оформлению акта или работе с QR. Спроси по делу."

    val suggestions: List<String> = listOf(
        "Что делать с находками?",
        "Списки запчастей",
        "Как оформить акт?",
        "Как навести QR?"
    )

    fun reply(message: String): String {
        val text = message.lowercase()
        return rules.firstOrNull { (keys, _) -> keys.any { text.contains(it) } }?.second ?: FALLBACK
    }
}
